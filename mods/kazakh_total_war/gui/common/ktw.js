function ktwCompatibleSave(game,info) {
 var m=game && game.metadata, attrs=m && m.initAttributes, settings=attrs && attrs.settings;
 if(!settings || !["campaign","battle"].includes(settings.KtwMode) || !info ||
    attrs.map!=="maps/random/ktw_"+settings.KtwMode ||
    m.engine_serialization_version!==info.engine_serialization_version ||
    !Array.isArray(m.mods) || !Array.isArray(info.mods))return false;
 var saved=m.mods.find(mod=>mod.mod==="kazakh_total_war");
 var current=info.mods.find(mod=>mod.mod==="kazakh_total_war");
 if(!saved || !current || (saved.version!=="0.1.0" && saved.version!==current.version))return false;
 var savedOther=m.mods.filter(mod=>mod.mod!=="kazakh_total_war" && !mod.ignoreInCompatibilityChecks);
 var currentOther=info.mods.filter(mod=>mod.mod!=="kazakh_total_war" && !mod.ignoreInCompatibilityChecks);
 return savedOther.length===currentOther.length && savedOther.every(mod=>currentOther.some(other=>other.mod===mod.mod && other.version===mod.version));
}
function ktwLatestSave() {
 var info=Engine.GetEngineInfo();
 return Engine.GetSavedGames().filter(game=>ktwCompatibleSave(game,info))
  .sort(function(a,b){return Number(b.metadata.time)-Number(a.metadata.time);})[0] || null;
}
